// Generates js/icons.js: inline Lucide icon paths for every icon name used in the source.
// Needs the "react-icons" package (a devDependency). Run: npm run icons
import fs from 'node:fs'; import path from 'node:path'; import { createRequire } from 'node:module';
const require = createRequire(process.env.ICON_SRC ? process.env.ICON_SRC + '/' : import.meta.url);
const lu = require('react-icons/lu');
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const files = []; (function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else if (p.endsWith('.js') && !p.endsWith('icons.js')) files.push(p); } })(path.join(root, 'js'));
const names = new Set();
for (const f of files) for (const m of fs.readFileSync(f, 'utf8').matchAll(/['"]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"]/g)) names.add(m[1]);
const pascal = (n) => 'Lu' + n.split('-').map(s => s[0].toUpperCase() + s.slice(1)).join('');
const out = {}, ch = (n) => (n.attrs && n.attrs.stroke ? '' : '');
function ser(nodes) { return nodes.map(n => '<' + n.tag + Object.entries(n.attr || {}).map(([k, v]) => ` ${k}="${v}"`).join('') + '/>').join(''); }
for (const n of names) {
  const C = lu[pascal(n)]; if (!C) continue;
  // react-icons components are function components that call GenIcon; render via a tiny shim.
  const React = require('react'), { renderToStaticMarkup } = require('react-dom/server');
  const svg = renderToStaticMarkup(React.createElement(C));
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  out[n] = inner;
}
fs.writeFileSync(path.join(root, 'js/icons.js'), '// Generated by tools/gen-icons.mjs from Lucide (ISC license).\nexport const ICONS = ' + JSON.stringify(out) + ';\n');
console.log('icons:', Object.keys(out).length);
